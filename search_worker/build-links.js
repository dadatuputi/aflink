// Bundles the site's link list into the worker. wrangler runs this before
// every deploy and `wrangler dev` (the "build" command in wrangler.jsonc), so
// when Cloudflare Workers Builds deploys on a push to master, the worker
// carries exactly the links that commit lists: no fetch of links.json at
// request time, no cache to expire.
//
// The list is assembled by scripts/assemble-links.js, the same code updater.js
// uses for the site, and written in the links.json shape the worker reads, cut
// down to the fields it uses. It needs no npm install: Workers Builds runs
// `cd search_worker && npx wrangler deploy` on a fresh checkout.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { readLinkFiles, assembleLinks, publishedLinks } from '../scripts/assemble-links.js'

const here = path.dirname(fileURLToPath(import.meta.url))
const linksDir = path.resolve(here, '../src/links')
const out = path.resolve(here, 'src/links.generated.js')

// What to_entries() in src/index.js reads; everything else is page display
const slim = ({ title, link, summary, description, isDeleted }) =>
  ({ title, link, summary, description, ...(isDeleted && { isDeleted }) })

export function buildLinks({ today = new Date().toISOString().slice(0, 10) } = {}) {
  const published = publishedLinks(assembleLinks(readLinkFiles(linksDir), { today }), { generated: today })
  return {
    metadata: published.metadata,
    links: published.links.map(({ category, links }) => ({ category, links: links.map(slim) })),
    unofficial: published.unofficial.map(slim),
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const data = buildLinks()
  fs.writeFileSync(out,
    '// Generated by search_worker/build-links.js from src/links/; do not edit.\n' +
    'export default ' + JSON.stringify(data) + '\n')
  console.log(`Bundled ${data.metadata.numLinks} links and ${data.metadata.numUnofficial} unofficial into ${path.relative(process.cwd(), out)}`)
}
